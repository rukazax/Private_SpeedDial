(async()=>{
    const checks=[];
    const check=(name,value)=>{checks.push({name,pass:!!value});if(!value)throw new Error('FAIL: '+name);};
    const sd=window._speedDial;
    check('initial tiles and secure origin',sd.tiles.length===2&&isSecureContext);
    check('no horizontal overflow',document.documentElement.scrollWidth<=innerWidth+1);
    const svg='data:image/svg+xml,'+encodeURIComponent('<svg xmlns="http://www.w3.org/2000/svg" width="32" height="32"><rect width="32" height="32" fill="teal"/></svg>');
    sd.showAddTileModal('https://example.org/android-test','Android тест');
    document.getElementById('tileAutoColor').checked=false;
    document.getElementById('tileIcon').value=svg;
    await sd.saveTileFromForm({preventDefault(){},target:document.getElementById('tileForm')});
    check('create bookmark through form',sd.tiles.some(t=>t.title==='Android тест')&&document.querySelectorAll('.tile:not(.add-tile)').length===3);
    const testTile=sd.tiles.find(t=>t.title==='Android тест');
    sd.showEditTileModal(testTile.id);
    document.getElementById('tileTitle').value='Android тест изменён';
    await sd.saveTileFromForm({preventDefault(){},target:document.getElementById('tileForm')});
    check('edit bookmark',sd.tiles.find(t=>t.id===testTile.id).title==='Android тест изменён');
    sd.showAddFolderModal();
    document.getElementById('folderName').value='Тестовая папка';
    document.getElementById('folderPassword').value='fixture-folder-pass';
    await sd.saveFolderFromForm({preventDefault(){},target:document.getElementById('folderForm')});
    const f=sd.folders.find(f=>f.name==='Тестовая папка');
    check('password folder hashing',f&&f.password.startsWith('pbkdf2$')&&await verifyFolderPassword('fixture-folder-pass',f.password));
    check('wrong folder password rejected',!await verifyFolderPassword('wrong',f.password));
    sd.showAddFolderModal();
    document.getElementById('folderName').value='Вложенная';
    document.getElementById('folderParent').value=f.id;
    await sd.saveFolderFromForm({preventDefault(){},target:document.getElementById('folderForm')});
    check('nested folder',sd.folders.some(x=>x.parentId===f.id));
    sd.showAddNoteModal();
    document.getElementById('noteTitle').value='Android заметка';
    document.getElementById('noteContent').value='Кириллица, перенос\nВторая строка';
    await sd.saveNoteFromForm({preventDefault(){},target:document.getElementById('noteForm')});
    check('note persistence',(await loadDataFromIDB()).notes.some(n=>n.content.includes('Вторая строка')));
    const rec=await createMasterPasswordRecord('fixture-master-pass');
    check('master password correct',await verifyMasterPassword('fixture-master-pass',rec));
    check('master password wrong',!await verifyMasterPassword('wrong',rec));
    const source={text:'Кириллица Android',tiles:sd.tiles};
    const encrypted=await encryptData(source,'fixture-encryption-pass');
    check('AES-GCM roundtrip',JSON.stringify(await decryptData(encrypted,'fixture-encryption-pass'))===JSON.stringify(source));
    let rejected=false;try{await decryptData(encrypted,'wrong');}catch(e){rejected=true;}
    check('AES-GCM rejects wrong key',rejected);
    const html=await chrome.runtime.sendMessage({action:'exportToHTML'});
    check('HTML export contains bookmark',JSON.stringify(html).includes('example.org'));
    sd.showContextMenu(20,20,testTile.id);
    check('context menu and Android Back',document.getElementById('contextMenu').style.display==='block'&&androidBack());
    const uiData=await loadDataFromIDB();
    const bgData=await chrome.runtime.sendMessage({action:'getSyncState'});
    check('background message response',bgData!==null&&typeof bgData==='object');
    return {checks,counts:{tiles:uiData.tiles.length,folders:uiData.folders.length,notes:uiData.notes.length}};
})()
